def main_worker(target: str, out: Path) -> int:
    sys.path.insert(0, str(ROOT))
    import tempfile
    import time
    from dataclasses import replace

    from PySide6.QtCore import QRect, Qt
    from PySide6.QtGui import QFontMetrics
    from PySide6.QtWidgets import (
        QAbstractButton,
        QAbstractScrollArea,
        QApplication,
        QLabel,
        QLayout,
        QWidget,
    )

    from core.converter import Phase
    from core.errors import classify_error
    from core.jobqueue import ItemSnapshot, JobQueue
    from core.updater import UpdateKind, UpdateResult
    from ui import theme
    from ui.input_panel import problems_for
    from ui.queue_delegate import BADGES, RowFonts, action_for
    from ui.widgets import ElidedLabel

    theme.configure_high_dpi()
    app = QApplication([])
    theme.apply_theme(app)
    from ui.main_window import MainWindow

    class NeverRuns:
        def __init__(self, *args) -> None:
            pass

        def run(self):  # pragma: no cover - the script never queues links
            raise RuntimeError("no conversions in the screenshot script")

        def stop(self) -> None:
            pass

    def settle(rounds: int = 8) -> None:
        for _ in range(rounds):
            app.processEvents()
            time.sleep(0.005)

    # Paths shown on screen only; nothing is written there.
    fake_root = Path(tempfile.gettempdir()) / "screenshot-matrix-not-used"
    window = MainWindow(queue_factory=lambda bridge: JobQueue(NeverRuns, **bridge.callbacks()))
    window.confirm = lambda *args: True
    window.versions.set("2025.10.22")  # placeholder, so no yt-dlp lookup runs
    window.setAttribute(Qt.WidgetAttribute.WA_DontShowOnScreen, True)
    window.show()
    settle()

    def snap(item_id: str, **changes) -> ItemSnapshot:
        base = ItemSnapshot(
            id=item_id, batch_id="b", batch_created=1.0,
            url=f"https://www.youtube.com/watch?v=vid{item_id:0>8}", video_id=f"vid{item_id:0>8}",
            title=f"Song {item_id}", phase=Phase.WAITING, percent=None, error=None,
        )
        return replace(base, **changes)

    staged = fake_root / "ready" / "x.mp3"
    long_title = ("【官方MV】周杰倫 Jay Chou【告白氣球 Love Confession】超長標題測試 Official Music Video "
                  "4K Remastered Extended Version with Lyrics 中文字幕 English Subtitles (2016)")
    long_url = "https://www.youtube.com/watch?v=dQw4w9WgXcQ&list=PL" + "x" * 90 + "&index=42&t=1234s"
    rows = [
        snap("1", title="Downloading song (Official Video)", phase=Phase.DOWNLOADING, percent=42.0),
        snap("2", title="Converting song", phase=Phase.CONVERTING),
        snap("3", title="Failed song", phase=Phase.FAILED, error=classify_error("ERROR: unexpected error 1234")),
        snap("4", title=long_title, phase=Phase.DONE, staged_path=staged),
        snap("5", title="", url=long_url, phase=Phase.WAITING),
        snap("6", title="Waiting song", phase=Phase.WAITING),
        snap("7", title="Ready song", phase=Phase.DONE, staged_path=staged),
        snap("8", title="Saved song", phase=Phase.DONE, staged_path=staged,
             saved_path=fake_root / "Downloads" / "Saved song.mp3"),
        snap("9", title="Stopped song", phase=Phase.STOPPED),
    ]
    links_text = "\n".join([
        "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
        "https://youtu.be/9bZkp7q19f0",
        "not a youtube link at all",
        "https://www.youtube.com/watch?v=kJQP7kiw5Fk",
        "https://music.youtube.com/watch?v=OPf0YbXqDm0",
    ])

    # --- checks -----------------------------------------------------------------

    def in_scroll_content(widget: QWidget, root: QWidget) -> bool:
        parent = widget.parentWidget()
        while parent is not None and parent is not root:
            grand = parent.parentWidget()
            if isinstance(grand, QAbstractScrollArea) and parent is grand.viewport():
                return True
            parent = grand
        return False

    def layout_widgets(layout: QLayout) -> list[QWidget]:
        found: list[QWidget] = []
        for index in range(layout.count()):
            item = layout.itemAt(index)
            if item.widget() is not None:
                found.append(item.widget())
            elif item.layout() is not None:
                found.extend(layout_widgets(item.layout()))
        return found

    def name_of(widget: QWidget) -> str:
        text = widget.text()[:24] if isinstance(widget, (QLabel, QAbstractButton)) else ""
        return f"{type(widget).__name__}({widget.objectName() or text})"

    def check_widgets(root: QWidget, problems: list[str], info: list[str]) -> None:
        bounds = root.rect()
        for widget in root.findChildren(QWidget):
            if not widget.isVisible() or widget.isWindow() or in_scroll_content(widget, root):
                continue
            box = QRect(widget.mapTo(root, widget.rect().topLeft()), widget.size())
            if box.width() and box.height() and not bounds.contains(box):
                problems.append(f"outside window: {name_of(widget)} {box.getRect()}")
        for widget in [root, *root.findChildren(QWidget)]:
            if not widget.isVisible() or widget.layout() is None:
                continue
            children = [child for child in layout_widgets(widget.layout()) if child.isVisible()]
            for i, first in enumerate(children):
                for second in children[i + 1:]:
                    if first.geometry().intersects(second.geometry()):
                        problems.append(f"overlap: {name_of(first)} / {name_of(second)}")
        for label in root.findChildren(QLabel):
            if not label.isVisible() or not label.text():
                continue
            if isinstance(label, ElidedLabel):
                width = QFontMetrics(label.font()).horizontalAdvance(label.text())
                if width > label.contentsRect().width():
                    info.append(f"elided by design (tooltip): {name_of(label)}")
            elif label.wordWrap():
                need = label.heightForWidth(label.width())
                if label.height() + 1 < need:
                    problems.append(f"clipped wrapped label: {name_of(label)} {label.height()} < {need}")
            else:
                need = QFontMetrics(label.font()).horizontalAdvance(label.text())
                if need > label.contentsRect().width() + 1:
                    problems.append(f"elided label: {name_of(label)} {label.contentsRect().width()} < {need}")
        for button in root.findChildren(QAbstractButton):
            if not button.isVisible() or not button.text():
                continue
            hint = button.sizeHint()
            if button.width() + 1 < hint.width() or button.height() + 1 < min(hint.height(), button.minimumHeight() or hint.height()):
                problems.append(f"elided button: {name_of(button)} {button.size().toTuple()} < {hint.toTuple()}")

    def check_rows(problems: list[str], info: list[str], size: str) -> None:
        view = window.queue_panel.view
        model = window.model
        if not model.rowCount():
            return
        delegate = view.delegate
        fonts = RowFonts.from_font(view.font())
        # Metric checks below only mean something if rows are measured with
        # the font they are painted with (Windows gives item views 9 pt).
        if abs(view.font().pointSizeF() - theme.FONT.body) > 0.01:
            problems.append(f"row font {view.font().pointSizeF():g} pt != body {theme.FONT.body:g} pt")
        bold, badge = QFontMetrics(fonts.bold), QFontMetrics(fonts.badge)
        viewport = view.viewport().rect()
        normal = delegate.row_height(rows[0], fonts)
        full_rows = 0
        for row in range(model.rowCount()):
            index = model.index(row)
            rect = view.visualRect(index)
            if viewport.contains(rect):
                full_rows += 1
            item = model.item(row)
            g = delegate.row_geometry(rect, item, view.font())
            parts = {"title": g.title, "line2": g.line2, "badge": g.badge, "button": g.button}
            if g.line3 is not None:
                parts["line3"] = g.line3
            names = list(parts)
            for i, first in enumerate(names):
                for second in names[i + 1:]:
                    a, b = parts[first], parts[second]
                    if a.width() and b.width() and a.intersects(b):
                        problems.append(f"row {row + 1}: {first} overlaps {second}")
            if bold.horizontalAdvance(action_for(item).label) > g.button.width():
                problems.append(f"row {row + 1}: button text elided")
            if badge.horizontalAdvance(BADGES[item.status].label) > g.badge.width():
                problems.append(f"row {row + 1}: badge text elided")
            expected = delegate.row_height(item, fonts)
            if rect.height() != expected:
                problems.append(f"row {row + 1}: height {rect.height()} != {expected}")
        rows_fit = viewport.height() // max(1, normal)
        info.append(f"{rows_fit} rows fit ({full_rows} fully visible)")
        if size == SMALLEST and rows_fit < MIN_QUEUE_ROWS:
            problems.append(f"only {rows_fit} queue rows fit at {size}")

    def check_convert(problems: list[str]) -> None:
        convert = window.input_panel.convert_button
        box = QRect(convert.mapTo(window, convert.rect().topLeft()), convert.size())
        if not convert.isVisible() or not window.rect().contains(box):
            problems.append(f"Convert not fully visible {box.getRect()}")
        elif convert.height() < convert.minimumHeight():
            problems.append("Convert shorter than its minimum")

    # --- captures -----------------------------------------------------------------

    def save(widget: QWidget, size: str, capture: str, logical: tuple[int, int],
             problems: list[str], info: list[str]) -> None:
        pixmap = widget.grab()
        name = f"dpr{target}_{size}_{capture}.png"
        pixmap.save(str(out / name))
        dpr = widget.devicePixelRatioF()
        if abs(dpr - float(target)) > 0.01:
            problems.append(f"effective DPR {dpr:g} != target {target}")
        print(json.dumps({
            "file": name, "capture": capture, "size": size, "dpr": round(dpr, 4),
            "logical": list(logical), "image": [pixmap.width(), pixmap.height()],
            "problems": problems, "info": info,
        }, ensure_ascii=False), flush=True)

    def capture_window(size: str, capture: str) -> None:
        width, height = (int(v) for v in size.split("x"))
        window.resize(width, height)
        settle()
        problems: list[str] = []
        info: list[str] = []
        if (window.width(), window.height()) != (width, height):
            problems.append(f"window is {window.width()}x{window.height()}, not {size}")
        check_widgets(window, problems, info)
        check_convert(problems)
        if capture == "mixed":
            check_rows(problems, info, size)
        save(window, size, capture, (window.width(), window.height()), problems, info)

    def capture_dialog(dialog, size: str, capture: str) -> None:
        width, height = (int(v) for v in size.split("x"))
        dialog.resize(dialog.sizeHint())
        settle()
        problems: list[str] = []
        info: list[str] = []
        if dialog.width() > width or dialog.height() > height:
            problems.append(f"dialog {dialog.width()}x{dialog.height()} larger than the {size} window")
        check_widgets(dialog, problems, info)
        save(dialog, size, capture, (dialog.width(), dialog.height()), problems, info)

    def set_rows(present: bool) -> None:
        if present:
            for row in rows:
                window.model.apply(row)
        else:
            window.model.remove([row.id for row in rows])
        window.queue_panel.update_header()
        settle()

    def set_links(present: bool) -> None:
        input_box = window.input_panel.input
        if present:
            input_box.setPlainText(links_text)
            input_box.set_problems(problems_for(links_text))
            window.input_panel.update_counter()
        else:
            window.input_panel.clear()
        settle()

    long_folder = Path("C:/Users/a.very.long.user.name/OneDrive - Some Company Name/Music/"
                       "Downloaded from YouTube/Converted MP3 files")
    for size in SIZES:
        capture_window(size, "empty")
        set_rows(True)
        capture_window(size, "mixed")
        set_rows(False)
        set_links(True)
        capture_window(size, "links")
        set_links(False)

        window.services.settings.set_save_dir(long_folder)  # in memory only
        settings = window.open_settings()
        settings.setAttribute(Qt.WidgetAttribute.WA_DontShowOnScreen, True)
        settings.set_advanced_open(True)
        capture_dialog(settings, size, "settings")
        settings.close()
        window.services.settings.reset_save_dir()

        update = window.open_update()
        update.setAttribute(Qt.WidgetAttribute.WA_DontShowOnScreen, True)
        update._on_finished(UpdateResult(UpdateKind.FAILED, message="Couldn't update. Your current version still works.",
                                         details="network error: offline"))
        capture_dialog(update, size, "update")
        update.close()
        settle()

    window.queue.shutdown()
    window.close()
    settle()
    return 0


def main() -> int:
    if len(sys.argv) > 1 and sys.argv[1] == "--detect":
        return main_detect()
    if len(sys.argv) > 1 and sys.argv[1] == "--worker":
        return main_worker(sys.argv[2], Path(sys.argv[3]))
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--offscreen", action="store_true", help="use Qt's offscreen platform")
    parser.add_argument("--out", default=str(ROOT / "screenshots"), help="output folder")
    parser.add_argument("--dprs", default=",".join(DPRS), help="comma-separated target DPRs")
    return main_parent(parser.parse_args())


if __name__ == "__main__":
    sys.exit(main())
