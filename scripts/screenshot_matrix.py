"""Render the real main window and dialogs to PNG at several sizes and DPRs.

Usage:
    python scripts/screenshot_matrix.py [--offscreen] [--out DIR] [--dprs 1.0,1.25,1.5]

* One subprocess per target DPR. Only inside that subprocess, QT_SCALE_FACTOR
  is set to ``target / system DPR`` so the EFFECTIVE devicePixelRatio equals
  the target on this machine (e.g. 0.8 on a 125 % screen gives 1.0). The app
  itself never sets any QT_* variable.
* Default: the real Windows platform (DirectWrite fonts, real DPR), windows
  rendered with WA_DontShowOnScreen so nothing flashes on the desktop and the
  OS does not clamp the window to the screen. ``--offscreen`` uses Qt's
  offscreen platform instead.
* Detached services: no real settings, no network, no real yt-dlp, never the
  real %LOCALAPPDATA% folder. Queue rows are fake snapshots (no conversions).
* Every capture is checked (widgets outside the window, overlapping
  siblings, elided/clipped button or label text, Convert visibility, queue
  rows at 910x440) and gets a PASS/FAIL line. Writes ``<out>/index.md``.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SIZES = ("910x440", "910x512", "1366x728", "1536x864")
DPRS = ("1.0", "1.25", "1.5")
CAPTURES = ("empty", "mixed", "links", "settings", "update")
MIN_QUEUE_ROWS = 3
SMALLEST = "910x440"


# --- parent process -------------------------------------------------------------


def _child_env(offscreen: bool, scale: float | None) -> dict[str, str]:
    env = {key: value for key, value in os.environ.items() if not key.startswith("QT_")}
    if offscreen:
        env["QT_QPA_PLATFORM"] = "offscreen"
        fonts = Path(os.environ.get("WINDIR", "C:/Windows")) / "Fonts"
        if fonts.is_dir():
            env["QT_QPA_FONTDIR"] = str(fonts)
    if scale is not None:
        env["QT_SCALE_FACTOR"] = repr(round(scale, 6))
    env["PYTHONIOENCODING"] = "utf-8"
    return env


def _run_child(args: list[str], env: dict[str, str]) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(Path(__file__).resolve()), *args],
        env=env, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", timeout=600,
    )


def detect_system_dpr(offscreen: bool) -> float:
    done = _run_child(["--detect"], _child_env(offscreen, None))
    if done.returncode != 0:
        raise SystemExit(f"could not start Qt:\n{done.stderr[-2000:]}")
    return float(done.stdout.strip().splitlines()[-1])


def main_parent(options: argparse.Namespace) -> int:
    out = Path(options.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    system = detect_system_dpr(options.offscreen)
    platform = "offscreen" if options.offscreen else "windows"
    print(f"platform: {platform}, system DPR: {system:g}, output: {out}")
    results: list[dict] = []
    for target in options.dprs.split(","):
        scale = float(target) / system
        print(f"\n== target DPR {target}: QT_SCALE_FACTOR={scale:g} (subprocess only)")
        done = _run_child(["--worker", target, str(out)], _child_env(options.offscreen, scale))
        lines = [json.loads(line) for line in done.stdout.splitlines() if line.startswith("{")]
        if done.returncode != 0 and not lines:
            print(done.stderr[-3000:])
            results.append({"file": "-", "target": target, "capture": "all", "size": "-", "dpr": 0,
                            "image": [0, 0], "problems": [f"worker crashed: {done.returncode}"], "info": []})
            continue
        for result in lines:
            result["target"] = target
            status = "PASS" if not result["problems"] else "FAIL"
            print(f"{status}  {result['file']:<34} effective DPR {result['dpr']:<5g} "
                  f"logical {result['logical'][0]}x{result['logical'][1]:<5} "
                  f"image {result['image'][0]}x{result['image'][1]}"
                  + ("" if not result["problems"] else "  <- " + "; ".join(result["problems"])))
            results.append(result)
        if done.returncode != 0:
            print(done.stderr[-3000:])
    write_index(out, results, platform, system)
    failed = [r for r in results if r["problems"]]
    print(f"\n{len(results) - len(failed)} PASS, {len(failed)} FAIL -> {out / 'index.md'}")
    return 1 if failed else 0


def write_index(out: Path, results: list[dict], platform: str, system: float) -> None:
    lines = [
        "# Screenshot matrix",
        "",
        f"Platform: `{platform}` · system DPR {system:g} · generated by `scripts/screenshot_matrix.py`.",
        "Logical sizes are the window's client area; images are in device pixels.",
        "Rows are fake snapshots; the yt-dlp version shown in Settings is a placeholder.",
        "",
        "| Result | File | Capture | Logical size | Effective DPR | Image px | Notes |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in results:
        notes = "; ".join(r["problems"] + r.get("info", [])) or ""
        lines.append(
            f"| {'PASS' if not r['problems'] else '**FAIL**'} | [{r['file']}]({r['file']}) | {r['capture']} "
            f"| {r.get('logical', ['-', '-'])[0]}x{r.get('logical', ['-', '-'])[1]} | {r['dpr']:g} "
            f"| {r['image'][0]}x{r['image'][1]} | {notes.replace('|', '/')} |"
        )
    (out / "index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


# --- worker process -------------------------------------------------------------


def main_detect() -> int:
    from PySide6.QtWidgets import QApplication

    sys.path.insert(0, str(ROOT))
    from ui import theme

    theme.configure_high_dpi()
    app = QApplication([])
