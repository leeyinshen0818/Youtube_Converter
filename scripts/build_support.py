"""Build-time helpers for build_windows.ps1 (not part of the app).

Usage (from the project folder):
  python scripts/build_support.py version
      print APP_VERSION from core/version.py
  python scripts/build_support.py version-info OUT
      write the PyInstaller version resource for APP_VERSION
  python scripts/build_support.py icon PNG OUT
      write a multi-size .ico (pads the PNG to a square; needs Pillow)
  python scripts/build_support.py zip FOLDER OUT
      zip FOLDER (as one top-level folder) into OUT, replacing OUT
  python scripts/build_support.py ytdlp FOLDER
      download the latest official yt-dlp.exe into FOLDER, verified against
      the release's SHA2-256SUMS (core/updater.py); exit code 1 on any problem

Only the ``ytdlp`` command uses the network.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path
from typing import Callable

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from core import updater  # noqa: E402
from core.version import APP_VERSION  # noqa: E402

PRODUCT_NAME = "YouTube to MP3 Converter"
EXE_BASENAME = "YouTubeMP3Converter"
ICON_SIZES = (16, 20, 24, 32, 40, 48, 64, 128, 256)


# --- version resource -----------------------------------------------------------


def version_tuple(version: str) -> tuple[int, int, int, int]:
    """"2.0.0" or "2.0.0-dev" -> (2, 0, 0, 0)."""
    match = re.match(r"^(\d+)\.(\d+)\.(\d+)(?:\.(\d+))?", version.strip())
    if not match:
        raise ValueError(f"not a version: {version!r}")
    return tuple(int(part or 0) for part in match.groups())  # type: ignore[return-value]


def version_info_text(version: str = APP_VERSION) -> str:
    numbers = version_tuple(version)
    return f"""# Generated by scripts/build_support.py from core/version.py; do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={numbers},
    prodvers={numbers},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [
          StringStruct('FileDescription', '{PRODUCT_NAME}'),
          StringStruct('FileVersion', '{version}'),
          StringStruct('InternalName', '{EXE_BASENAME}'),
          StringStruct('OriginalFilename', '{EXE_BASENAME}.exe'),
          StringStruct('ProductName', '{PRODUCT_NAME}'),
          StringStruct('ProductVersion', '{version}')
        ]
      )
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def write_version_info(out: Path, version: str = APP_VERSION) -> None:
    Path(out).write_text(version_info_text(version), encoding="utf-8", newline="\n")


# --- icon -------------------------------------------------------------------------


def square_image(image):
    """Trim fully transparent margins, then pad (never crop the picture) to a
    square on a transparent background, centered: the artwork fills as much
    of each icon size as its shape allows."""
    from PIL import Image

    image = image.convert("RGBA")
    box = image.getchannel("A").getbbox()
    if box:
        image = image.crop(box)
    side = max(image.size)
    if image.width == image.height:
        return image
    square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    square.paste(image, ((side - image.width) // 2, (side - image.height) // 2))
    return square


def write_icon(png: Path, out: Path, sizes: tuple[int, ...] = ICON_SIZES) -> list[tuple[int, int]]:
    """Each size is resampled separately from the full-size image (Lanczos),
    so small sizes stay sharp. Returns the sizes stored in the file."""
    from PIL import Image

    with Image.open(png) as source:
        square = square_image(source)
    frames = [square.resize((size, size), Image.Resampling.LANCZOS) for size in sorted(sizes)]
    largest = frames[-1]
    largest.save(out, format="ICO", sizes=[frame.size for frame in frames], append_images=frames[:-1])
    with Image.open(out) as written:
        stored = sorted(written.info.get("sizes") or written.ico.sizes())
    expected = sorted((size, size) for size in sizes)
    if stored != expected:
        raise RuntimeError(f"icon sizes {stored} != {expected}")
    return stored


# --- yt-dlp.exe ---------------------------------------------------------------------


class FetchError(Exception):
    pass


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as file:
        for chunk in iter(lambda: file.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def fetch_ytdlp(
    folder: Path,
    opener: updater.Opener | None = None,
    command_for: Callable[[Path], list[str]] = updater.default_command,
) -> tuple[Path, str]:
    """Download the latest official yt-dlp.exe into ``folder``.

    Reuses core.updater: official GitHub asset URLs only, size check, SHA-256
    against SHA2-256SUMS, ``--version`` must answer. Any old copy in
    ``folder`` is removed first so a failed download never leaves a stale
    file that the build would pick up. Returns (path, version).
    """
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / updater.EXE_NAME
    for name in (updater.EXE_NAME, updater.BACKUP_NAME):
        (folder / name).unlink(missing_ok=True)
    result = updater.update_ytdlp(
        updater.UpdateRequest(
            tools_dir=folder,
            current_exe=None,
            opener=opener or updater.default_opener(),
            command_for=command_for,
        )
    )
    if result.kind is not updater.UpdateKind.INSTALLED or not target.is_file():
        target.unlink(missing_ok=True)
        raise FetchError(result.details or result.message or result.kind.value)
    return target, result.version


# --- zip ----------------------------------------------------------------------------


def write_zip(folder: Path, out: Path) -> int:
    """Zip ``folder`` so it unpacks as one folder; returns the file count."""
    import zipfile

    folder, out = Path(folder), Path(out)
    files = sorted(path for path in folder.rglob("*") if path.is_file())
    temp = out.with_name(out.name + ".partial")
    with zipfile.ZipFile(temp, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for path in files:
            archive.write(path, (Path(folder.name) / path.relative_to(folder)).as_posix())
    temp.replace(out)
    return len(files)


# --- command line -------------------------------------------------------------------


def main(
    argv: list[str] | None = None,
    opener: updater.Opener | None = None,
    command_for: Callable[[Path], list[str]] = updater.default_command,
) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("version")
    info = commands.add_parser("version-info")
    info.add_argument("out", type=Path)
    icon = commands.add_parser("icon")
    icon.add_argument("png", type=Path)
    icon.add_argument("out", type=Path)
    zipped = commands.add_parser("zip")
    zipped.add_argument("folder", type=Path)
    zipped.add_argument("out", type=Path)
    ytdlp = commands.add_parser("ytdlp")
    ytdlp.add_argument("folder", type=Path)
    args = parser.parse_args(argv)

    if args.command == "version":
        print(APP_VERSION)
    elif args.command == "version-info":
        write_version_info(args.out)
        print(f"Version resource for {APP_VERSION}: {args.out}")
    elif args.command == "icon":
        sizes = write_icon(args.png, args.out)
        print(f"Icon with sizes {', '.join(str(w) for w, _ in sizes)}: {args.out}")
    elif args.command == "zip":
        count = write_zip(args.folder, args.out)
        print(f"Zipped {count} files: {args.out}")
    elif args.command == "ytdlp":
        try:
            path, version = fetch_ytdlp(args.folder, opener, command_for)
        except FetchError as exc:
            print(f"ERROR: yt-dlp.exe download or verification FAILED: {exc}", file=sys.stderr)
            return 1
        print(f"yt-dlp {version} verified against SHA2-256SUMS (sha256 {sha256_of(path)}): {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
